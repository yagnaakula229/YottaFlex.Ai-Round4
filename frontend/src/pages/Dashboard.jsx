import { useCallback, useEffect, useState } from 'react'
import { api } from '../services/api.js'
import { Distribution, ErrorState, LoadingState, MetricCard, PriorityBadge, StatusBadge } from '../components/Ui.jsx'
import { formatDate } from '../services/format.js'

const priorityColors = { P1: '#c8484c', P2: '#db8a36', P3: '#d2ad49', P4: '#5c91bd' }
const accountColors = { P1: '#c8484c', P2: '#db8a36', P3: '#d2ad49', P4: '#5c91bd', UNASSESSED: '#8792a2' }

function Dashboard({ refreshKey, onNavigate }) {
  const [data, setData] = useState(null)
  const [alerts, setAlerts] = useState([])
  const [cases, setCases] = useState([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const load = useCallback(async () => {
    try {
      const [summary, alertPage, casePage] = await Promise.all([
        api.dashboard(),
        api.alerts({ limit: 5 }),
        api.cases({ limit: 5 }),
      ])
      setData(summary)
      setAlerts(alertPage.items)
      setCases(casePage.items)
    } catch (loadError) {
      setError(loadError.message)
    } finally {
      setLoading(false)
    }
  }, [])

  useEffect(() => { load() }, [load, refreshKey])

  if (loading) return <LoadingState label="Loading dashboard from the operational API…" />
  if (error) return <ErrorState error={error} onRetry={() => { setError(''); setLoading(true); load() }} />

  return (
    <div className="page-stack">
      <section className="metric-grid">
        <MetricCard label="Total transactions" value={data.total_transactions.toLocaleString()} detail="Recorded in the operational ledger" icon="↔" />
        <MetricCard label="Total alerts" value={data.total_alerts.toLocaleString()} detail="Generated by risk rules" icon="⌁" tone="orange" />
        <MetricCard label="Open cases" value={data.open_cases.toLocaleString()} detail="Open, in review, or escalated" icon="▤" tone="violet" />
        <MetricCard label="Suspicious outcomes" value={data.suspicious_transactions.toLocaleString()} detail="From analyst dispositions" icon="◉" tone="green" />
      </section>

      <section className="distribution-grid">
        <Distribution title="Alert priority distribution" data={data.alerts_by_priority} colors={priorityColors} />
        <Distribution title="Account risk distribution" data={data.account_risk_distribution} colors={accountColors} />
      </section>

      <section className="panel">
        <div className="panel-heading">
          <div><p className="eyebrow">Most recently detected</p><h2>Recent alerts</h2></div>
          <button className="text-button" onClick={() => onNavigate('alerts')}>View all alerts <span aria-hidden="true">→</span></button>
        </div>
        {alerts.length ? (
          <div className="table-scroll"><table>
            <thead><tr><th>Alert</th><th>Rule</th><th>Priority</th><th>Status</th><th>Detected</th></tr></thead>
            <tbody>{alerts.map((alert) => (
              <tr key={alert.alert_id}>
                <td><strong className="mono">{alert.alert_id}</strong><small className="cell-subtitle">{alert.triggering_transaction_id}</small></td>
                <td>{alert.rule_key.replaceAll('_', ' ')}</td>
                <td><PriorityBadge value={alert.priority} /></td>
                <td><StatusBadge value={alert.status} /></td>
                <td>{formatDate(alert.detected_at)}</td>
              </tr>
            ))}</tbody>
          </table></div>
        ) : <p className="muted panel-empty">No alerts are available.</p>}
      </section>

      <section className="panel">
        <div className="panel-heading">
          <div><p className="eyebrow">Analyst queue</p><h2>Recently updated cases</h2></div>
          <button className="text-button" onClick={() => onNavigate('cases')}>Open case workspace <span aria-hidden="true">→</span></button>
        </div>
        {cases.length ? (
          <div className="table-scroll"><table>
            <thead><tr><th>Case</th><th>Alerts</th><th>Priority</th><th>Status</th><th>Updated</th></tr></thead>
            <tbody>{cases.map((item) => (
              <tr key={item.case_id}>
                <td><strong className="mono">{item.case_id}</strong><small className="cell-subtitle">{item.title}</small></td>
                <td>{item.alert_count}</td>
                <td><PriorityBadge value={item.priority} /></td>
                <td><StatusBadge value={item.status} /></td>
                <td>{formatDate(item.updated_at)}</td>
              </tr>
            ))}</tbody>
          </table></div>
        ) : <p className="muted panel-empty">No cases are available.</p>}
      </section>
      <p className="data-note">Dashboard metrics are served by the backend. Evaluation ground truth is isolated from operational risk signals.</p>
    </div>
  )
}

export default Dashboard
